"""Build data/lists/allowlist_trackerradar.txt from the DuckDuckGo Tracker Radar clone.

    python3 tools/build_allowlist.py [--radar ml/data/tracker-radar] [--max-fingerprinting 0]

A domain is infrastructure if Tracker Radar tags it CDN or Non-Tracking, tags it with none
of the tracking/social/ad categories below, and its fingerprinting score is <= the limit.
Reproducible from the public dataset; no hand-picking from our own captures.
"""
import argparse
import glob
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TRACKING = {"Advertising", "Ad Motivated Tracking", "Analytics", "Action Pixels", "Session Replay",
            "Audience Measurement", "Third-Party Analytics Marketing", "Ad Fraud", "Social - Share",
            "Social - Comment", "Social Network", "Unknown High Risk Behavior", "Malware",
            "Obscure Ownership", "Fraud Prevention", "Tag Manager"}


def build(radar, max_fp=0, region="US"):
    out = set()
    for p in glob.glob(os.path.join(radar, "domains", region, "*.json")):
        with open(p) as f:
            d = json.load(f)
        cats = set(d.get("categories", []))
        if cats & {"CDN", "Non-Tracking"} and not cats & TRACKING and d.get("fingerprinting", 0) <= max_fp:
            out.add(d["domain"].lower())
    return sorted(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--radar", default=os.path.join(ROOT, "ml", "data", "tracker-radar"))
    ap.add_argument("--max-fingerprinting", type=int, default=0)
    ap.add_argument("--out", default=os.path.join(ROOT, "data", "lists", "allowlist_trackerradar.txt"))
    a = ap.parse_args()
    doms = build(a.radar, a.max_fingerprinting)
    with open(a.out, "w") as f:
        f.write("# Generated by tools/build_allowlist.py from DuckDuckGo Tracker Radar (CDN / Non-Tracking,\n"
                "# no tracking categories, fingerprinting <= %d). Do not edit by hand.\n" % a.max_fingerprinting)
        f.write("\n".join(doms) + "\n")
    print(f"{len(doms)} domains -> {a.out}")


if __name__ == "__main__":
    main()
